export const BLOG_LABELS: Record<string, IBlogLabels> = { en, es }

/** The dictionary for a BCP 47 locale (`es-MX` → `es`, unknown → `en`) with the site's overrides on top. */
export function resolveBlogLabels(locale: string | undefined, overrides: Partial<IBlogLabels> = {}): IBlogLabels {
  const language = (locale || 'en').toLowerCase().split('-')[0]!
  return { ...en, ...BLOG_LABELS[language], ...overrides }
}

/** Fills `{placeholder}`s; unknown placeholders are left as they are. */
export function formatLabel(text: string, params: Record<string, string | number> = {}): string {
  return text.replace(/\{(\w+)\}/g, (match, key: string) => (key in params ? String(params[key]) : match))
}
